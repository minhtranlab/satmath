#!/usr/bin/env python3
"""Skill taxonomy → src/Skills.gs (the Skills tab + names the app shows).
   python3 tools/build_skills.py "<project folder>/taxonomy/sml_skills.csv" "<project folder>/reuse/taxonomy/sat_skills.csv"
Only codes and names are written (domain, College Board skill, sub-skill) — no descriptions, traps or example items.
`skill` = the official College Board skill of the row; it is never derived from the sub-skill code."""
import csv, json, os, sys

sml, cb = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
cb_rows = [r for r in csv.DictReader(open(cb, encoding='utf-8')) if r['section'] == 'Math']
cb_name = {r['skill']: r['skill_name'] for r in cb_rows}
dom_name = {r['domain']: r['domain_name'] for r in cb_rows}
rows, seen = [], set()
for r in csv.DictReader(open(sml, encoding='utf-8')):
    sk, ss = r['skill'].strip(), r['subskill'].strip()
    assert sk in cb_name, 'unknown CB skill %s (row %s)' % (sk, ss)
    assert ss and ss not in seen, 'sub-skill missing or twice: %s' % ss
    seen.add(ss)
    rows.append({'domain': r['domain'].strip(), 'domain_name': dom_name.get(r['domain'].strip(), r['domain_name']),
                 'skill': sk, 'skill_name': cb_name[sk], 'subskill': ss, 'subskill_name': r['subskill_name'].strip()})
# every CB skill appears (a skill with no sub-skill yet gets one row with an empty sub-skill)
for r in cb_rows:
    if not any(x['skill'] == r['skill'] for x in rows):
        rows.append({'domain': r['domain'], 'domain_name': r['domain_name'], 'skill': r['skill'], 'skill_name': r['skill_name'], 'subskill': '', 'subskill_name': ''})
order = {r['skill']: i for i, r in enumerate(cb_rows)}
rows.sort(key=lambda x: (order[x['skill']], [int(p) if p.isdigit() else p for p in x['subskill'].split('.')]))
out = ('// GENERATED by tools/build_skills.py from taxonomy/sml_skills.csv + reuse/taxonomy/sat_skills.csv — do not edit by hand.\n'
       '// domain → College Board skill → sub-skill (codes + names only). %d sub-skills under %d CB skills.\n'
       'var SKILLS_ = %s;\n') % (len(seen), len(cb_rows), json.dumps(rows, ensure_ascii=False, indent=0).replace('\n', ''))
open(os.path.join(HERE, '..', 'src', 'Skills.gs'), 'w', encoding='utf-8').write(out)
print('Skills.gs: %d sub-skills, %d CB skills' % (len(seen), len(cb_rows)))
